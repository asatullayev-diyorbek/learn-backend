"""
Core business logic for Telegram authentication.

Kept separate from views/bot handlers so both the DRF API and the aiogram
bot call the exact same code paths. Nothing here ever logs or returns a raw
token/code once it has been hashed and stored.
"""

import hashlib
import hmac
import secrets
from typing import Optional, Tuple

from django.conf import settings
from django.db import transaction
from django.utils import timezone

from .models import TelegramAuthChallenge, TelegramIdentity, TelegramLoginCode, User

CHALLENGE_TTL_SECONDS = 10 * 60
CODE_TTL_SECONDS = 5 * 60
CODE_RATE_LIMIT_SECONDS = 60


def _hash_value(raw_value: str) -> str:
    """HMAC-SHA256 the value with SECRET_KEY as key.

    This is a one-way hash used purely so the raw token/code never sits in
    the DB in plaintext; we don't need per-record salts since each raw
    value is already a single-use, high-entropy secret generated by us (not
    a user-chosen password reused elsewhere).
    """
    return hmac.new(
        settings.SECRET_KEY.encode(), raw_value.encode(), hashlib.sha256
    ).hexdigest()


# --------------------------------------------------------------------------
# Shared: find-or-create the Learn user for a Telegram id
# --------------------------------------------------------------------------


def get_or_create_user_for_telegram(
    telegram_id: int,
    username: Optional[str] = "",
    first_name: Optional[str] = "",
    last_name: Optional[str] = "",
) -> User:
    """Look up the user linked to telegram_id, creating one if needed.

    A telegram_id can never end up linked to more than one User: the lookup
    and creation happen inside one atomic block, and TelegramIdentity.
    telegram_id is unique=True as the DB-level backstop.
    """
    username = username or ""
    first_name = first_name or ""
    last_name = last_name or ""

    with transaction.atomic():
        identity = (
            TelegramIdentity.objects.select_for_update()
            .filter(telegram_id=telegram_id)
            .select_related("user")
            .first()
        )
        if identity is not None:
            # Refresh the snapshot (people change their TG username/name).
            changed = False
            if identity.telegram_username != username:
                identity.telegram_username = username
                changed = True
            if identity.first_name != first_name:
                identity.first_name = first_name
                changed = True
            if identity.last_name != last_name:
                identity.last_name = last_name
                changed = True
            if changed:
                identity.save(
                    update_fields=["telegram_username", "first_name", "last_name", "updated_at"]
                )
            return identity.user

        user = User.objects.create(
            username=f"tg_{telegram_id}",
            first_name=first_name[:150],
        )
        user.set_unusable_password()
        user.save(update_fields=["password"])

        TelegramIdentity.objects.create(
            user=user,
            telegram_id=telegram_id,
            telegram_username=username,
            first_name=first_name,
            last_name=last_name,
        )
        return user


# --------------------------------------------------------------------------
# Flow 1: deep-link / one-time token
# --------------------------------------------------------------------------


def create_auth_challenge(ip: Optional[str] = None) -> Tuple[str, TelegramAuthChallenge]:
    """Create a new pending auth challenge. Returns (raw_token, challenge)."""
    raw_token = secrets.token_urlsafe(32)
    challenge = TelegramAuthChallenge.objects.create(
        token_hash=_hash_value(raw_token),
        status=TelegramAuthChallenge.STATUS_PENDING,
        created_ip=ip,
        expires_at=timezone.now() + timezone.timedelta(seconds=CHALLENGE_TTL_SECONDS),
    )
    return raw_token, challenge


def confirm_auth_challenge(
    raw_token: str,
    telegram_id: int,
    username: Optional[str] = "",
    first_name: Optional[str] = "",
    last_name: Optional[str] = "",
) -> Tuple[Optional[User], Optional[str]]:
    """Confirm a challenge from the bot side.

    Returns (user, None) on success, or (None, error) where error is one of
    "not_found", "used", "expired".
    """
    token_hash = _hash_value(raw_token)

    with transaction.atomic():
        challenge = (
            TelegramAuthChallenge.objects.select_for_update()
            .filter(token_hash=token_hash)
            .first()
        )
        if challenge is None:
            return None, "not_found"

        if challenge.status == TelegramAuthChallenge.STATUS_CONFIRMED:
            return None, "used"

        if challenge.is_expired():
            return None, "expired"

        user = get_or_create_user_for_telegram(telegram_id, username, first_name, last_name)

        challenge.status = TelegramAuthChallenge.STATUS_CONFIRMED
        challenge.user = user
        challenge.telegram_id = telegram_id
        challenge.confirmed_at = timezone.now()
        challenge.save(
            update_fields=["status", "user", "telegram_id", "confirmed_at"]
        )
        return user, None


def get_auth_challenge_status(raw_token: str) -> Optional[TelegramAuthChallenge]:
    """Fetch the challenge for a raw token, or None if it doesn't exist."""
    token_hash = _hash_value(raw_token)
    return TelegramAuthChallenge.objects.filter(token_hash=token_hash).first()


def mark_challenge_session_issued(challenge: TelegramAuthChallenge) -> None:
    challenge.session_issued_at = timezone.now()
    challenge.save(update_fields=["session_issued_at"])


# --------------------------------------------------------------------------
# Flow 2: 5-digit /login code
# --------------------------------------------------------------------------


def create_login_code(
    telegram_id: int,
    username: Optional[str] = "",
    first_name: Optional[str] = "",
    last_name: Optional[str] = "",
) -> Tuple[Optional[str], Optional[str]]:
    """Create a new 5-digit login code for telegram_id.

    Returns (raw_code, None) on success, or (None, "rate_limited") if the
    same telegram_id requested a code within the last
    CODE_RATE_LIMIT_SECONDS seconds.
    """
    cutoff = timezone.now() - timezone.timedelta(seconds=CODE_RATE_LIMIT_SECONDS)
    recent_exists = TelegramLoginCode.objects.filter(
        telegram_id=telegram_id, created_at__gte=cutoff
    ).exists()
    if recent_exists:
        return None, "rate_limited"

    raw_code = f"{secrets.randbelow(100000):05d}"
    TelegramLoginCode.objects.create(
        code_hash=_hash_value(raw_code),
        telegram_id=telegram_id,
        telegram_username=username or "",
        first_name=first_name or "",
        last_name=last_name or "",
        expires_at=timezone.now() + timezone.timedelta(seconds=CODE_TTL_SECONDS),
    )
    return raw_code, None


def verify_login_code(raw_code: str) -> Tuple[Optional[User], Optional[str]]:
    """Verify a 5-digit code.

    Returns (user, None) on success, or (None, error) where error is one of
    "invalid", "used", "expired".
    """
    code_hash = _hash_value(raw_code)

    with transaction.atomic():
        code = (
            TelegramLoginCode.objects.select_for_update().filter(code_hash=code_hash).first()
        )
        if code is None:
            return None, "invalid"

        if code.used_at is not None:
            return None, "used"

        if code.is_expired():
            return None, "expired"

        user = get_or_create_user_for_telegram(
            code.telegram_id, code.telegram_username, code.first_name, code.last_name
        )

        code.used_at = timezone.now()
        code.save(update_fields=["used_at"])
        return user, None
